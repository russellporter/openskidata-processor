#!/bin/bash

# PostgreSQL initialization script for openskidata-processor

set -e

echo "Starting PostgreSQL initialization..."

# Configure PostgreSQL to listen on all addresses
echo "Configuring PostgreSQL to listen on all addresses..."
# Needs to be done each time as the data dir doesnt hold this file
sed -i "s/#listen_addresses = 'localhost'/listen_addresses = '*'/" /etc/postgresql/17/main/postgresql.conf

# Configure authentication based on whether custom user/password are set
if [ -n "$POSTGRES_USER" ] && [ -n "$POSTGRES_PASSWORD" ]; then
    echo "Configuring PostgreSQL with password authentication..."
    # Needs to be done each time as the data dir doesnt hold this file
    tee "/etc/postgresql/17/main/pg_hba.conf" > /dev/null << EOF
# TYPE  DATABASE        USER            ADDRESS                 METHOD
local   all             all                                     trust
host    all             all             127.0.0.1/32            md5
host    all             all             ::1/128                 md5
host    all             all             0.0.0.0/0               md5
EOF
else
    echo "Configuring PostgreSQL with trust authentication..."
    tee "/etc/postgresql/17/main/pg_hba.conf" > /dev/null << EOF
# TYPE  DATABASE        USER            ADDRESS                 METHOD
local   all             all                                     trust
host    all             all             127.0.0.1/32            trust
host    all             all             ::1/128                 trust
host    all             all             0.0.0.0/0               trust
EOF
fi

# Update PostgreSQL config to use the data directory
sed -i "s|data_directory = '/var/lib/postgresql/17/main'|data_directory = '/var/lib/postgresql/data'|" /etc/postgresql/17/main/postgresql.conf

# Tuning. Written as a conf.d drop-in (included by the Debian packaging) rather than
# edited into postgresql.conf, so re-running this script cannot duplicate settings.
#
# The processor's heaviest database work is the per-run clustering database: bulk load,
# GiST and GIN index builds, ST_Union aggregates, large sorts, and a continuous stream of
# full-row UPDATEs. On the stock initdb defaults that runs with shared_buffers=128MB and
# work_mem=4MB, which is far too small for the working set.
#
# Durability is deliberately traded away. The clustering database is created fresh per run
# (CREATE DATABASE "clustering-<timestamp>-<random>") and thrown away afterwards, and the
# three caches can be refetched, so there is nothing here worth surviving a crash. If the
# machine dies mid-run the run is restarted regardless.
echo "Applying PostgreSQL tuning..."
TOTAL_MEM_MB=$(awk '/MemTotal/ { printf "%d", $2 / 1024 }' /proc/meminfo)
# Fall back to a conservative figure if /proc/meminfo is unreadable.
if [ -z "$TOTAL_MEM_MB" ] || [ "$TOTAL_MEM_MB" -lt 1024 ]; then
    TOTAL_MEM_MB=1024
fi
PG_SHARED_BUFFERS_MB=${PG_SHARED_BUFFERS_MB:-$((TOTAL_MEM_MB / 4))}
PG_EFFECTIVE_CACHE_SIZE_MB=${PG_EFFECTIVE_CACHE_SIZE_MB:-$((TOTAL_MEM_MB * 3 / 4))}
# work_mem is per sort node, not per connection, and the clustering pool is small (10),
# so this can be generous relative to total memory.
PG_WORK_MEM_MB=${PG_WORK_MEM_MB:-$((TOTAL_MEM_MB / 32))}
if [ "$PG_WORK_MEM_MB" -lt 16 ]; then PG_WORK_MEM_MB=16; fi
PG_MAINTENANCE_WORK_MEM_MB=${PG_MAINTENANCE_WORK_MEM_MB:-$((TOTAL_MEM_MB / 8))}
if [ "$PG_MAINTENANCE_WORK_MEM_MB" -lt 64 ]; then PG_MAINTENANCE_WORK_MEM_MB=64; fi
PG_MAX_PARALLEL_WORKERS=${PG_MAX_PARALLEL_WORKERS:-$(nproc)}

mkdir -p /etc/postgresql/17/main/conf.d
tee /etc/postgresql/17/main/conf.d/10-openskidata-tuning.conf > /dev/null << EOF
# Generated by scripts/init-postgres.sh. Override any value by setting the matching
# PG_* environment variable before starting the container.

shared_buffers = ${PG_SHARED_BUFFERS_MB}MB
effective_cache_size = ${PG_EFFECTIVE_CACHE_SIZE_MB}MB
work_mem = ${PG_WORK_MEM_MB}MB
maintenance_work_mem = ${PG_MAINTENANCE_WORK_MEM_MB}MB

# Index builds and the bulk load are the slowest phases; let them use every core.
max_worker_processes = ${PG_MAX_PARALLEL_WORKERS}
max_parallel_workers = ${PG_MAX_PARALLEL_WORKERS}
max_parallel_workers_per_gather = ${PG_MAX_PARALLEL_WORKERS}
max_parallel_maintenance_workers = ${PG_MAX_PARALLEL_WORKERS}

# See the comment in scripts/init-postgres.sh: nothing in this instance needs to survive
# a crash, so the WAL is configured for throughput rather than durability.
fsync = off
synchronous_commit = off
full_page_writes = off
wal_level = minimal
max_wal_senders = 0
wal_compression = off
max_wal_size = 8GB
min_wal_size = 1GB
checkpoint_timeout = 30min
checkpoint_completion_target = 0.9

# The clustering tables are written once, indexed, then read and updated heavily within a
# single run. Autovacuum has no time to help and only competes for I/O.
autovacuum = off

# SSD-oriented planner costs; the data directory is a container volume, not a spindle.
random_page_cost = 1.1
effective_io_concurrency = 200

# JIT costs more than it saves on these queries, which are index lookups and aggregates
# rather than long analytical scans.
jit = off
EOF

# Initialize PostgreSQL if not already initialized
if [ ! -f /var/lib/postgresql/data/PG_VERSION ]; then
    echo "Initializing PostgreSQL database..."
    echo "Setting up data directory permissions..."
    chown -R postgres:postgres /var/lib/postgresql/data
    chmod 700 /var/lib/postgresql/data
    su - postgres -c "/usr/lib/postgresql/17/bin/initdb -D /var/lib/postgresql/data"

    # Start PostgreSQL temporarily to create user if needed
    echo "Starting PostgreSQL for initialization..."
    if ! su - postgres -c "/usr/lib/postgresql/17/bin/pg_ctl -D /var/lib/postgresql/data -l /var/log/postgresql/postgresql-17-main.log start"; then
        echo "ERROR: Failed to start PostgreSQL"
        echo "Startup logs:"
        cat /var/log/postgresql/postgresql-17-main.log 2>&1 || echo "Log file not found"
        exit 1
    fi

    # Wait for PostgreSQL to be ready
    echo "Waiting for PostgreSQL to be ready..."
    for i in {1..30}; do
        if su - postgres -c "pg_isready -q"; then
            echo "PostgreSQL is ready"
            break
        fi
        if [ $i -eq 30 ]; then
            echo "ERROR: PostgreSQL failed to become ready within 30 seconds"
            echo "Startup logs:"
            cat /var/log/postgresql/postgresql-17-main.log 2>&1 || echo "Log file not found"
            exit 1
        fi
        sleep 1
    done
    
    # Create custom user if environment variables are set
    if [ -n "$POSTGRES_USER" ] && [ -n "$POSTGRES_PASSWORD" ]; then
        echo "Creating custom user: $POSTGRES_USER"
        su - postgres -c "psql -c \"CREATE USER $POSTGRES_USER WITH PASSWORD '$POSTGRES_PASSWORD' SUPERUSER;\""
    fi

    # Create application databases
    echo "Creating application databases..."
    su - postgres -c "psql -c \"CREATE DATABASE openskidata_cache;\""
    su - postgres -c "psql -c \"CREATE DATABASE openskidata_test;\""
    
    # Enable PostGIS extension on both databases
    echo "Enabling PostGIS extensions..."
    su - postgres -c "psql -c \"CREATE EXTENSION IF NOT EXISTS postgis;\" openskidata_cache"
    su - postgres -c "psql -c \"CREATE EXTENSION IF NOT EXISTS postgis;\" openskidata_test"
    
    # Stop PostgreSQL
    su - postgres -c "/usr/lib/postgresql/17/bin/pg_ctl -D /var/lib/postgresql/data stop"
fi

# Start PostgreSQL as the main process
echo "Starting PostgreSQL..."
if ! su - postgres -c "/usr/lib/postgresql/17/bin/pg_ctl -t 180 -w -D /var/lib/postgresql/data -l /var/log/postgresql/postgresql-17-main.log start"; then
    echo "ERROR: Failed to start PostgreSQL"
    echo "Startup logs:"
    cat /var/log/postgresql/postgresql-17-main.log 2>&1 || echo "Log file not found"
    exit 1
fi

# Clean up clustering databases older than 1 day
echo "Checking for old clustering databases to clean up..."
su - postgres -c "psql -At -c \"SELECT 'DROP DATABASE IF EXISTS \\\"' || datname || '\\\";' FROM pg_database WHERE datname LIKE 'clustering-%' AND (pg_stat_file('base/'||oid ||'/PG_VERSION')).modification < NOW() - INTERVAL '1 day'\" | psql"

# Keep container running by tailing PostgreSQL logs
echo "PostgreSQL initialization complete. Tailing logs..."
exec tail -f /var/log/postgresql/postgresql-17-main.log
