#!/usr/bin/env node
/**
 * Generates `rust/crates/openskidata-format/src/generated/enums.rs` by importing the
 * real `openskidata-format` package at runtime.
 *
 * The enum string values are the wire format: they land in GeoJSON properties, CSV
 * cells, GeoPackage TEXT columns and MVT attributes, and openskimap.org reads them.
 * Hand-typing them into Rust would make a single typo a silent data corruption that
 * no type system catches, so they are generated instead and checked in. Re-run after
 * every `openskidata-format` bump; CI diffs the result.
 *
 * Usage: node rust/codegen/generate-format-enums.mjs [--check]
 */
import { writeFileSync, readFileSync, mkdirSync, existsSync } from "node:fs";
import { execFileSync } from "node:child_process";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const repoRoot = join(here, "..", "..");
const outPath = join(
  repoRoot,
  "rust/crates/openskidata-format/src/generated/enums.rs",
);

const pkg = JSON.parse(
  readFileSync(
    join(repoRoot, "node_modules/openskidata-format/package.json"),
    "utf8",
  ),
);
const mod = await import("openskidata-format");

/** A TS string enum compiles to an object whose values are all distinct strings. */
function isStringEnum(value) {
  if (typeof value !== "object" || value === null || Array.isArray(value))
    return false;
  const entries = Object.entries(value);
  if (entries.length === 0) return false;
  return entries.every(
    ([k, v]) => typeof k === "string" && typeof v === "string",
  );
}

/** `classic+skating` / `t-bar` / `skimap.org` -> `ClassicAndSkating` / `TBar` / `SkimapOrg` */
function variantName(tsKey, wireValue) {
  // Prefer the TS key when it is already PascalCase and alphanumeric; it carries the
  // author's intent (e.g. `ClassicAndSkating` for `classic+skating`). SCREAMING_CASE
  // keys get re-cased.
  const source =
    /^[A-Za-z][A-Za-z0-9]*$/.test(tsKey) && tsKey !== tsKey.toUpperCase()
      ? tsKey
      : tsKey.toLowerCase();
  return source
    .split(/[^A-Za-z0-9]+/)
    .filter(Boolean)
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join("");
}

const enums = Object.entries(mod)
  .filter(([, v]) => isStringEnum(v))
  .sort(([a], [b]) => a.localeCompare(b));

if (enums.length === 0) {
  throw new Error(
    "No string enums found in openskidata-format — did its build layout change?",
  );
}

const lines = [];
lines.push(
  "// @generated by rust/codegen/generate-format-enums.mjs — DO NOT EDIT BY HAND.",
);
lines.push(`// Source: openskidata-format@${pkg.version}`);
lines.push("//");
lines.push("// Re-generate with:  node rust/codegen/generate-format-enums.mjs");
lines.push(
  "// Verify in CI with: node rust/codegen/generate-format-enums.mjs --check",
);
lines.push("");
lines.push("use serde::{Deserialize, Serialize};");
lines.push("");

for (const [enumName, members] of enums) {
  const entries = Object.entries(members);
  lines.push(`/// \`${enumName}\` from openskidata-format@${pkg.version}.`);
  lines.push(
    "#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, PartialOrd, Ord, Serialize, Deserialize)]",
  );
  lines.push("#[repr(u8)]");
  lines.push(`pub enum ${enumName} {`);
  for (const [k, v] of entries) {
    lines.push(`    #[serde(rename = ${JSON.stringify(v)})]`);
    lines.push(`    ${variantName(k, v)},`);
  }
  lines.push("}");
  lines.push("");
  lines.push(`impl ${enumName} {`);
  lines.push("    /// Every variant, in declaration order.");
  lines.push(`    pub const ALL: &'static [${enumName}] = &[`);
  for (const [k, v] of entries)
    lines.push(`        ${enumName}::${variantName(k, v)},`);
  lines.push("    ];");
  lines.push("");
  lines.push(
    "    /// The wire value. This string is the public contract — never change it here.",
  );
  lines.push("    pub const fn as_wire_str(self) -> &'static str {");
  lines.push("        match self {");
  for (const [k, v] of entries) {
    lines.push(
      `            ${enumName}::${variantName(k, v)} => ${JSON.stringify(v)},`,
    );
  }
  lines.push("        }");
  lines.push("    }");
  lines.push("}");
  lines.push("");
  lines.push(`impl core::fmt::Display for ${enumName} {`);
  lines.push(
    "    fn fmt(&self, f: &mut core::fmt::Formatter<'_>) -> core::fmt::Result {",
  );
  lines.push("        f.write_str(self.as_wire_str())");
  lines.push("    }");
  lines.push("}");
  lines.push("");
  lines.push(`impl core::str::FromStr for ${enumName} {`);
  lines.push("    type Err = crate::UnknownWireValue;");
  lines.push("    fn from_str(s: &str) -> Result<Self, Self::Err> {");
  lines.push("        match s {");
  for (const [k, v] of entries) {
    lines.push(
      `            ${JSON.stringify(v)} => Ok(${enumName}::${variantName(k, v)}),`,
    );
  }
  lines.push("            other => Err(crate::UnknownWireValue {");
  lines.push(`                enum_name: ${JSON.stringify(enumName)},`);
  lines.push("                value: other.to_owned(),");
  lines.push("            }),");
  lines.push("        }");
  lines.push("    }");
  lines.push("}");
  lines.push("");
}

/**
 * Run the emitted source through rustfmt, so the checked-in file is both
 * rustfmt-clean (CI runs `cargo fmt --check`) and byte-stable against `--check`.
 * Without this the two checks fight each other.
 */
function rustfmt(source) {
  try {
    return execFileSync(
      "rustfmt",
      ["--edition", "2024", "--emit", "stdout", "--quiet"],
      {
        input: source,
        encoding: "utf8",
        stdio: ["pipe", "pipe", "pipe"],
      },
    );
  } catch (error) {
    console.warn(
      "rustfmt unavailable or failed; emitting unformatted source. " +
        "`cargo fmt --check` will likely fail until rustfmt is installed.",
      error?.message ?? error,
    );
    return source;
  }
}

const generated = rustfmt(lines.join("\n"));

if (process.argv.includes("--check")) {
  const existing = existsSync(outPath) ? readFileSync(outPath, "utf8") : "";
  if (existing !== generated) {
    console.error(
      `${outPath} is out of date with openskidata-format@${pkg.version}.\n` +
        "Run: node rust/codegen/generate-format-enums.mjs",
    );
    process.exit(1);
  }
  console.log(`enums.rs is up to date with openskidata-format@${pkg.version}`);
} else {
  mkdirSync(dirname(outPath), { recursive: true });
  writeFileSync(outPath, generated);
  console.log(
    `Wrote ${enums.length} enums (${enums.map(([n]) => n).join(", ")}) ` +
      `from openskidata-format@${pkg.version}`,
  );
}
