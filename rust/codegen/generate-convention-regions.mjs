#!/usr/bin/env node
/**
 * Generates `rust/crates/openskidata-format/src/generated/convention_regions.rs` from the
 * region polygons embedded in the installed `openskidata-format` package.
 *
 * `getRunDifficultyConvention` decides which colour convention a ski area uses by testing
 * its location against two polygons, and those polygons are private constants inside the
 * package's module rather than anything it exports. They are about 15 KB of coordinates,
 * which is exactly the sort of data that must not be retyped: a single transposed digit
 * would silently move a border.
 *
 * So they are extracted from the module text. That is more fragile than importing, and is
 * deliberately loud about it: if the package's layout changes so the declarations cannot be
 * found, or no longer parse as plain coordinate arrays, this fails rather than emitting
 * something plausible. The generated data is then verified end to end by comparing the Rust
 * lookup against the live implementation over a global grid (see
 * `generate-format-vectors.mjs`).
 *
 * Usage: node rust/codegen/generate-convention-regions.mjs [--check]
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { repoRoot, rustfmt } from "./tooling.mjs";

import { loadConventionRegions } from "./convention-data.mjs";

const outPath = join(
  repoRoot,
  "rust/crates/openskidata-format/src/generated/convention_regions.rs",
);
const pkg = JSON.parse(
  readFileSync(
    join(repoRoot, "node_modules/openskidata-format/package.json"),
    "utf8",
  ),
);

/** A Rust f64 literal that parses back to exactly the same value. */
function rustFloat(n) {
  if (Object.is(n, -0)) return "-0.0";
  const text = String(n);
  // `String` prints the shortest string that round-trips. Integers print without a
  // decimal point, which Rust would read as an integer literal.
  return /[.eE]/.test(text) ? text : `${text}.0`;
}

function emit(name, multiPolygon) {
  const polygons = multiPolygon
    .map(
      (polygon) =>
        `&[${polygon
          .map(
            (ring) =>
              `&[${ring.map(([x, y]) => `[${rustFloat(x)}, ${rustFloat(y)}]`).join(", ")}]`,
          )
          .join(", ")}]`,
    )
    .join(", ");
  return `pub const ${name}: MultiPolygon = &[${polygons}];`;
}

const { japan, northAmerica, japanVertices, northAmericaVertices } =
  loadConventionRegions();

const generated = rustfmt(
  [
    "// @generated by rust/codegen/generate-convention-regions.mjs — DO NOT EDIT BY HAND.",
    `// Source: openskidata-format@${pkg.version}, dist/RunDifficultyConvention.js`,
    "//",
    "// Re-generate with:  node rust/codegen/generate-convention-regions.mjs",
    "// Verify in CI with: node rust/codegen/generate-convention-regions.mjs --check",
    "//",
    `// japan: ${japan.length} polygon(s), ${japanVertices} vertices.`,
    `// north_america: ${northAmerica.length} polygon(s), ${northAmericaVertices} vertices.`,
    "//",
    "// Longitudes are not normalized to [-180, 180]: the North America region is stored with",
    "// values above 180 so that it is one contiguous polygon across the antimeridian. The",
    "// lookup depends on that, so do not wrap them.",
    "",
    "/// `[[x, y]]`, closed.",
    "pub type Ring = &'static [[f64; 2]];",
    "/// An outer ring followed by any holes.",
    "pub type Polygon = &'static [Ring];",
    "pub type MultiPolygon = &'static [Polygon];",
    "",
    emit("JAPAN", japan),
    "",
    emit("NORTH_AMERICA", northAmerica),
    "",
  ].join("\n"),
);

if (process.argv.includes("--check")) {
  const existing = existsSync(outPath) ? readFileSync(outPath, "utf8") : "";
  if (existing !== generated) {
    console.error(
      `${outPath} is out of date with openskidata-format@${pkg.version}.\n` +
        "Run: node rust/codegen/generate-convention-regions.mjs",
    );
    process.exit(1);
  }
  console.log(
    `convention_regions.rs is up to date with openskidata-format@${pkg.version}`,
  );
} else {
  mkdirSync(dirname(outPath), { recursive: true });
  writeFileSync(outPath, generated);
  console.log(
    `Wrote japan (${japanVertices} vertices) and north_america ` +
      `(${northAmericaVertices} vertices) from openskidata-format@${pkg.version}`,
  );
}
